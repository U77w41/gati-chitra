import type { Theme, ThemeId } from '../core/types';

function defTheme(
  id: ThemeId,
  name: string,
  background: string,
  nodeFill: string,
  nodeStroke: string,
  nodeText: string,
  edge: string,
  groupFill: string,
  groupStroke: string,
  groupTitle: string,
  particle: string,
  gridColor: string,
  glowDefault = false,
  backgroundGradient: [string, string] | null = null,
): Theme {
  return {
    id,
    name,
    background,
    backgroundGradient,
    nodeFill,
    nodeStroke,
    nodeText,
    edge,
    edgeLabelBg: background,
    edgeLabelText: nodeText,
    titleText: nodeText,
    groupFill,
    groupStroke,
    groupTitle,
    particle,
    glow: particle,
    selection: particle,
    glowDefault,
    gridColor,
  };
}

